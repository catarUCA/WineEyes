"""Ablacion de la representacion segmentada: dense-only, sparse-only y barrido de RRF k.

Complementa a eval.ablation_fusion (OCR vs VLM vs OCR+VLM) y a
eval.ablation_segmentation (full vs segments vs both): aqui se aisla la
contribucion de cada rama de recuperacion y la sensibilidad de la fusion a la
constante RRF, que es lo que pide la revision (2.8).

Para cada consulta lanza las dos busquedas de rama de Qdrant una sola vez
(via hybrid_branch_rankings) y deriva todas las configuraciones sin volver a
consultar:

  * dense-only  : ranking de la rama densa (semantico), truncado a 50;
  * sparse-only : ranking de la rama sparse (lexico); puede devolver < 50
                  etiquetas (solo co-ocurrencia lexica); las no recuperadas
                  cuentan como no relevantes;
  * RRF(k)      : fusion reciproca de ambas ramas para k en {10, 30, 60, 100}.

Todas las configuraciones usan la coleccion segmentada de produccion. Las
metricas son las mismas nDCG@10 y MAP@10 del resto de la evaluacion, de modo
que RRF(k=60) reproduce la fila del hibrido segmentado de la Tabla 2. Genera
results/table_ablation.tex y results/ablation.csv.

Ejecutar como eval.run_retrieval (Qdrant levantado, indices construidos, BGE-M3):

    export EVAL_QDRANT_MODE=local        # PowerShell: $env:EVAL_QDRANT_MODE="local"
    python -m eval.build_eval_indices --reset   # si no estan ya construidos
    python -m eval.ablation_rrf
"""

from __future__ import annotations

import csv
import sys

from eval.config import (
    METRICS_FULL_PATH,
    RESULTS_DIR,
    ensure_results_dir,
)
from eval.data_io import load_qrels, load_queries
from eval.embeddings import BGEEmbedder
from eval.metrics import metrics_for_ranking
from eval.qdrant_eval import hybrid_branch_rankings
from eval.retrieval_core import RankedLabel, reciprocal_rank_fusion
from eval.runtime import append_run_log, get_qdrant_client

SYSTEM = "ocr_vlm_hybrid_segmented"
RRF_KS = (10, 30, 60, 100)
FINAL_RESULTS = 50
METRICS = ("ndcg_at_10", "map_at_10")

ABLATION_TEX = RESULTS_DIR / "table_ablation.tex"
ABLATION_CSV = RESULTS_DIR / "ablation.csv"


def _truncate(ranking, n=FINAL_RESULTS):
    """Renumber a branch ranking to consecutive ranks and cap at n labels."""
    return [RankedLabel(item.eval_id, rank, item.score)
            for rank, item in enumerate(ranking[:n], 1)]


def _eval_ids(ranking):
    return [item.eval_id for item in ranking]


def _config_rankings(branches):
    """Build every ablation configuration from the two branch rankings."""
    dense = branches["dense"]
    sparse = branches["sparse"]
    configs = {
        "dense_only": _truncate(dense),
        "sparse_only": _truncate(sparse),
    }
    for k in RRF_KS:
        configs[f"rrf_k{k}"] = reciprocal_rank_fusion(branches, rrf_k=k,
                                                      final_results=FINAL_RESULTS)
    return configs


LABELS = {
    "dense_only": "Dense only (semantico)",
    "sparse_only": "Sparse only (lexico)",
    "rrf_k10": "Hybrid RRF, $k=10$",
    "rrf_k30": "Hybrid RRF, $k=30$",
    "rrf_k60": "Hybrid RRF, $k=60$ (default)",
    "rrf_k100": "Hybrid RRF, $k=100$",
}
ORDER = ["dense_only", "sparse_only", "rrf_k10", "rrf_k30", "rrf_k60", "rrf_k100"]


def render_table(agg, coverage):
    lines = [
        "% Generated by python -m eval.ablation. Do not edit manually.",
        "\\begin{table*}[!h]",
        "\\centering",
        "\\begin{tabular}{lcc}",
        "\\toprule",
        "\\textbf{Configuration (segmented)} & \\textbf{nDCG@10} & \\textbf{MAP@10} \\\\",
        "\\midrule",
    ]
    for key in ORDER:
        row = agg[key]
        bold = key == "rrf_k60"
        name = LABELS[key]
        nd = f"{row['ndcg_at_10']:.3f}"
        mp = f"{row['map_at_10']:.3f}"
        if bold:
            name = f"\\textbf{{{name}}}"
            nd = f"\\textbf{{{nd}}}"
            mp = f"\\textbf{{{mp}}}"
        lines.append(f"{name} & {nd} & {mp} \\\\")
        if key == "sparse_only":
            lines.append("\\midrule")
    cov = coverage["sparse_only"]
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Ablation on the segmented representation over the 15 queries. "
        "Dense-only and sparse-only use a single Qdrant branch; RRF rows fuse both. "
        f"The sparse branch returned on average {cov:.1f} of {FINAL_RESULTS} labels "
        "per query (lexical co-occurrence only); unretrieved labels count as "
        "non-relevant. RRF is largely insensitive to $k$ over $[10,100]$, and "
        "$k=60$ reproduces the segmented hybrid of Table~\\ref{tab:retrieval}.}",
        "\\label{tab:ablation}",
        "\\end{table*}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    ensure_results_dir()
    append_run_log("ablation started")
    try:
        client = get_qdrant_client()
        embedder = BGEEmbedder()
        queries = load_queries()
        gains, binary, _ = load_qrels()

        per_query = {key: {m: [] for m in METRICS} for key in ORDER}
        sparse_sizes = []
        rows_csv = []

        for query in queries:
            branches, _ = hybrid_branch_rankings(client, embedder, SYSTEM, query.text)
            sparse_sizes.append(len(branches["sparse"]))
            configs = _config_rankings(branches)
            for key in ORDER:
                vals = metrics_for_ranking(
                    _eval_ids(configs[key]),
                    gains[query.query_id],
                    binary[query.query_id],
                    True,
                )
                for m in METRICS:
                    per_query[key][m].append(float(vals[m]))
                rows_csv.append({
                    "query_id": query.query_id,
                    "config": key,
                    "ndcg_at_10": f"{vals['ndcg_at_10']:.6f}",
                    "map_at_10": f"{vals['map_at_10']:.6f}",
                })
            print(f"{query.query_id}: dense={len(branches['dense'])} "
                  f"sparse={len(branches['sparse'])}")

        agg = {key: {m: sum(v) / len(v) for m, v in per_query[key].items()} for key in ORDER}
        coverage = {"sparse_only": sum(sparse_sizes) / len(sparse_sizes)}

        ABLATION_TEX.write_text(render_table(agg, coverage), encoding="utf-8")
        with ABLATION_CSV.open("w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=["query_id", "config", "ndcg_at_10", "map_at_10"])
            writer.writeheader()
            writer.writerows(rows_csv)

        print("\n== Ablation (segmented) ==")
        for key in ORDER:
            print(f"  {LABELS[key]:32s} nDCG@10={agg[key]['ndcg_at_10']:.3f} "
                  f"MAP@10={agg[key]['map_at_10']:.3f}")
        print(f"\n  sparse branch mean coverage: {coverage['sparse_only']:.1f}/{FINAL_RESULTS}")
        print(f"  wrote {ABLATION_TEX} and {ABLATION_CSV}")
    except Exception as exc:  # noqa: BLE001
        append_run_log(f"ablation FAILED: {type(exc).__name__}: {exc}")
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    append_run_log("ablation completed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())